def seed() -> None:
    with SessionLocal() as db:
        for build in (build_renewable_energy_run, build_microservices_run):
            run = build()
            existing = db.get(Run, run.id)
            if existing is None:
                db.add(run)
        db.commit()
    print("Seeded example runs.")


