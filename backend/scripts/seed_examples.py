def _iso(dt: datetime) -> str:
    return dt.isoformat()


def _trace(base_time: datetime, node: str, minutes: float, summary: str) -> dict:
    return {
        "node": node,
        "timestamp": _iso(base_time + timedelta(minutes=minutes)),
        "summary": summary,
    }


